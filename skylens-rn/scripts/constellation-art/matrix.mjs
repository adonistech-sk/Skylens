// Writes the per-constellation completion matrix from the project's own data, so it can't drift
// from what actually ships. usage: node scripts/constellation-art/matrix.mjs <evidence.json> <out.md>
//   evidence.json holds the visual review: { "<Id>": "final" | "acceptable: reason", ... }
import fs from 'node:fs';
import { constellationIds, constellationPlane } from './sky.mjs';

const [reviewFile, out] = process.argv.slice(2);
const review = reviewFile && fs.existsSync(reviewFile) ? JSON.parse(fs.readFileSync(reviewFile, 'utf8')) : {};
const art = JSON.parse(fs.readFileSync(new URL('../../src/data/generated/constellationArt.json', import.meta.url), 'utf8'));
const stories = fs.readFileSync(new URL('../../src/data/constellationStories.ts', import.meta.url), 'utf8');
const byId = new Map(art.map((a) => [a.id, a]));
const PRIORITY = new Set(['Ori', 'UMa', 'UMi', 'Cas', 'Sco', 'Sgr', 'Tau', 'Leo', 'Cyg', 'And', 'Peg', 'Gem']);
/** The figures that were actually looked at in the running sky, not only as a print. */
const SEEN_IN_SKY = new Set([...PRIORITY, 'Lyr', 'Aql', 'Vir', 'Boo', 'Her', 'Per', 'Aur', 'Lib', 'Cap', 'CMa', 'Crt', 'Dra']);

const rows = constellationIds().map((id) => {
  const p = constellationPlane(id), a = byId.get(id);
  const verdict = review[id];
  const status = !a ? 'not drawn' : verdict === 'final' ? 'final' : verdict ? 'acceptable' : 'unreviewed';
  const told = new RegExp(`\\b${id}: \\{ origin: '\\w+'[^\\n]*traditions: \\[\\]`).test(stories) ? 'history' : 'history + traditions';
  return {
    id, name: p.name, tier: PRIORITY.has(id) ? 'priority' : 'other', status, sky: !a ? '—' : SEEN_IN_SKY.has(id) ? 'yes' : 'print only', note: typeof verdict === 'string' && verdict !== 'final' ? verdict.replace(/^acceptable:?\s*/, '') : '',
    anchors: a ? `${a.anchors.length}, ${a.onFigure.lineStars}/${a.onFigure.lineTotal} on figure` : '—', geometry: `${p.stars.length} stars`, animation: a ? 'lines, trace, plate' : 'lines only', told, size: a ? `${Math.round(a.bytes / 1024)} KB` : '—',
  };
});

const count = (s) => rows.filter((r) => r.status === s).length;
const md = [
  '# Constellation completion matrix',
  '',
  'Generated by `scripts/constellation-art/matrix.mjs` from the shipped data. Do not edit by hand.',
  '',
  `Artwork: **${count('final')} final**, **${count('acceptable')} acceptable**, ${count('unreviewed')} unreviewed, **${count('not drawn')} not drawn**, of 88.`,
  '',
  '- **Artwork.** `final`: an original vector figure that meets the bar in review. `acceptable`: original and shipped, with a named weakness. `not drawn`: no illustration exists, and the app shows the real lines and stars with no substitute. None is a procedural placeholder: each figure was composed individually for its own stars.',
  '- **Seen in sky.** Whether the figure was reviewed by eye in the running sky. `print only` means the plate was reviewed on black, and only its anchoring was measured in place.',
  '- **Geometry.** Every line star is from the catalog, and every constellation has lines, boundary and search.',
  '- **Anchoring.** Number of named anchor stars, and how many of the figure\'s line stars land on the drawing. Every anchored figure passes the same measured test.',
  '- **Animation.** All 88 reveal their lines. A drawn figure adds the outline trace and the plate.',
  '- **Story.** All 88 have science and history. Traditions appear where a real, attributable one exists.',
  '',
  '| Id | Constellation | Tier | Artwork | Seen in sky | Weakness | Geometry | Anchoring | Animation | Story | Plate |',
  '|---|---|---|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${r.name} | ${r.tier} | ${r.status} | ${r.sky} | ${r.note} | ${r.geometry} | ${r.anchors} | ${r.animation} | ${r.told} | ${r.size} |`),
  '',
].join('\n');
fs.writeFileSync(out, md);
console.log({ final: count('final'), acceptable: count('acceptable'), unreviewed: count('unreviewed'), notDrawn: count('not drawn') });
