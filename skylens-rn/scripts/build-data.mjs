// Generates the app's data modules from the Swift package's catalog resources. The
// values are copied, never edited, so the two apps cannot disagree about the sky.
import fs from 'node:fs';

const res = new URL('../../Packages/SkyLensKit/Sources/SkyCatalog/Resources/', import.meta.url);
const out = new URL('../src/data/generated/', import.meta.url);
fs.mkdirSync(out, { recursive: true });

const bin = fs.readFileSync(new URL('stars.bin', res));
if (bin.toString('latin1', 0, 4) !== 'SKS1') throw new Error('bad stars.bin');
const n = bin.readUInt32LE(4);
const RECORD = 28;
const constellations = JSON.parse(fs.readFileSync(new URL('constellations.json', res), 'utf8'));
const lineStars = new Set(constellations.flatMap((c) => c.lines.flat()));
const MAG_LIMIT = 6.8;

const rows = [];
const seen = new Set();
for (let i = 0; i < n; i++) {
  const o = 8 + i * RECORD;
  const hip = bin.readUInt32LE(o);
  const mag = bin.readInt16LE(o + 24) / 100;
  if (mag > MAG_LIMIT && !lineStars.has(hip)) continue;
  rows.push(o);
  seen.add(hip);
}
for (const h of lineStars) if (!seen.has(h)) throw new Error(`constellation star ${h} missing from stars.bin`);

// hip u32, ra f32, dec f32, pmra f32, pmdec f32, mag i16, bv i16, parallax f32: 26 → padded to 28.
const packed = Buffer.alloc(rows.length * RECORD);
rows.forEach((o, i) => bin.copy(packed, i * RECORD, o, o + RECORD));
fs.writeFileSync(new URL('stars.ts', out),
  `// Generated by scripts/build-data.mjs from Hipparcos via stars.bin. Do not edit.\n` +
  `export const STAR_COUNT = ${rows.length};\nexport const STAR_RECORD = ${RECORD};\n` +
  `export const STARS_B64 = '${packed.toString('base64')}';\n`);

const meta = fs.readFileSync(new URL('stars-meta.tsv', res), 'utf8').trim().split('\n').map((l) => l.split('\t'));
const metaRows = meta.filter((f) => seen.has(Number(f[0])) || f[1]).map((f) => [Number(f[0]), f[1] || 0, f[2] || 0, f[3] || 0, f[4] ? Number(f[4]) : 0, f[5] ? Number(f[5]) : 0, f[6] || 0]);
const deep = fs.readFileSync(new URL('deepsky.tsv', res), 'utf8').trim().split('\n').map((l) => l.split('\t')).map((f) => [
  f[0], f[1] ? Number(f[1]) : 0, f[2] || 0, f[3], Number(f[4]), Number(f[5]), f[6] ? Number(f[6]) : null, f[7] ? Number(f[7]) : null, f[8] ? Number(f[8]) : null,
]);
fs.writeFileSync(new URL('catalog.json', out), JSON.stringify({
  starMeta: metaRows,
  deepSky: deep,
  constellations: constellations.map(({ id, name, genitive, lines, center }) => ({ id, name, genitive, lines, center })),
}));
fs.copyFileSync(new URL('editorial.json', res), new URL('editorial.json', out));
fs.copyFileSync(new URL('provenance.json', res), new URL('provenance.json', out));
console.log({ stars: rows.length, bytes: packed.length, meta: metaRows.length, deep: deep.length, constellations: constellations.length });
