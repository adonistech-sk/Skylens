// Generates the app's data modules from the Swift package's catalog resources. The
// values are copied, never edited, so the two apps cannot disagree about the sky.
import crypto from 'node:crypto';
import fs from 'node:fs';
import { CELL_COUNT, cellOf, crc32, GRID_SIDE, PACK_DIRECTORY_ENTRY, PACK_HEADER, PACK_MAGIC, PACK_RECORD, PACK_VERSION, packRecordsOffset } from '../src/data/catalogs/grid.ts';

const res = new URL('../../Packages/SkyLensKit/Sources/SkyCatalog/Resources/', import.meta.url);
const out = new URL('../src/data/generated/', import.meta.url);
fs.mkdirSync(out, { recursive: true });

const bin = fs.readFileSync(new URL('stars.bin', res));
if (bin.toString('latin1', 0, 4) !== 'SKS1') throw new Error('bad stars.bin');
const n = bin.readUInt32LE(4);
const RECORD = 28;
const constellations = JSON.parse(fs.readFileSync(new URL('constellations.json', res), 'utf8'));
const lineStars = new Set(constellations.flatMap((c) => c.lines.flat()));
// Faint stars are for depth when zoomed in, so only those down to META_LIMIT carry names
// and spectral data. The rest are positions and colours from the same catalog.
const MAG_LIMIT = 8.0, META_LIMIT = 6.8;

const rows = [];
const seen = new Set(), described = new Set();
for (let i = 0; i < n; i++) {
  const o = 8 + i * RECORD;
  const hip = bin.readUInt32LE(o);
  const mag = bin.readInt16LE(o + 24) / 100;
  if (mag > MAG_LIMIT && !lineStars.has(hip)) continue;
  rows.push(o);
  seen.add(hip);
  if (mag <= META_LIMIT || lineStars.has(hip)) described.add(hip);
}
for (const h of lineStars) if (!seen.has(h)) throw new Error(`constellation star ${h} missing from stars.bin`);

// hip u32, ra f32, dec f32, pmra f32, pmdec f32, mag i16, bv i16, parallax f32: 26 → padded to 28.
const packed = Buffer.alloc(rows.length * RECORD);
rows.forEach((o, i) => bin.copy(packed, i * RECORD, o, o + RECORD));
fs.writeFileSync(new URL('stars.ts', out),
  `// Generated by scripts/build-data.mjs from Hipparcos via stars.bin. Do not edit.\n` +
  `export const STAR_COUNT = ${rows.length};\nexport const STAR_RECORD = ${RECORD};\n` +
  `export const STARS_B64 = '${packed.toString('base64')}';\n`);

const meta = fs.readFileSync(new URL('stars-meta.tsv', res), 'utf8').trim().split('\n').map((l) => l.split('\t'));
const metaRows = meta.filter((f) => described.has(Number(f[0])) || f[1]).map((f) => [Number(f[0]), f[1] || 0, f[2] || 0, f[3] || 0, f[4] ? Number(f[4]) : 0, f[5] ? Number(f[5]) : 0, f[6] || 0]);
const deep = fs.readFileSync(new URL('deepsky.tsv', res), 'utf8').trim().split('\n').map((l) => l.split('\t')).map((f) => [
  f[0], f[1] ? Number(f[1]) : 0, f[2] || 0, f[3], Number(f[4]), Number(f[5]), f[6] ? Number(f[6]) : null, f[7] ? Number(f[7]) : null, f[8] ? Number(f[8]) : null,
]);
fs.writeFileSync(new URL('catalog.json', out), JSON.stringify({
  starMeta: metaRows,
  deepSky: deep,
  constellations: constellations.map(({ id, name, genitive, lines, center }) => ({ id, name, genitive, lines, center })),
}));
fs.copyFileSync(new URL('editorial.json', res), new URL('editorial.json', out));
fs.copyFileSync(new URL('provenance.json', res), new URL('provenance.json', out));

// ---- The deep star pack ----
// Every Hipparcos star the bundle above leaves out, grouped by sky cell so the app can read
// one patch of sky at a time. These are the same records from the same file: no new source,
// and no value is changed. Records keep the format of stars.bin.
const base = new Set(rows);
const deepRows = [];
for (let i = 0; i < n; i++) {
  const o = 8 + i * RECORD;
  if (base.has(o)) continue;
  const ra = (bin.readFloatLE(o + 4) * Math.PI) / 180, dec = (bin.readFloatLE(o + 8) * Math.PI) / 180;
  deepRows.push({ o, cell: cellOf(Math.cos(dec) * Math.cos(ra), Math.cos(dec) * Math.sin(ra), Math.sin(dec)), mag: bin.readInt16LE(o + 24) });
}
deepRows.sort((a, b) => a.cell - b.cell || a.mag - b.mag || a.o - b.o);
const recordsAt = packRecordsOffset();
const pack = Buffer.alloc(recordsAt + deepRows.length * PACK_RECORD);
pack.write(PACK_MAGIC, 0, 'latin1');
[PACK_VERSION, deepRows.length, CELL_COUNT, GRID_SIDE, PACK_RECORD].forEach((v, i) => pack.writeUInt32LE(v, 4 + i * 4));
const firstRow = new Uint32Array(CELL_COUNT + 1).fill(deepRows.length);
for (let r = deepRows.length - 1; r >= 0; r--) firstRow[deepRows[r].cell] = r;
for (let c = CELL_COUNT - 1; c >= 0; c--) firstRow[c] = Math.min(firstRow[c], firstRow[c + 1]);
deepRows.forEach((r, i) => bin.copy(pack, recordsAt + i * PACK_RECORD, r.o, r.o + PACK_RECORD));
for (let c = 0; c <= CELL_COUNT; c++) {
  const at = PACK_HEADER + c * PACK_DIRECTORY_ENTRY;
  pack.writeUInt32LE(firstRow[c], at);
  if (c === CELL_COUNT) continue;
  let fastest = 0;
  for (let r = firstRow[c]; r < firstRow[c + 1]; r++) {
    const o = recordsAt + r * PACK_RECORD;
    fastest = Math.max(fastest, Math.hypot(pack.readFloatLE(o + 12), pack.readFloatLE(o + 16)));
  }
  pack.writeFloatLE(fastest, at + 4);
  pack.writeUInt32LE(crc32(pack.subarray(recordsAt + firstRow[c] * PACK_RECORD, recordsAt + firstRow[c + 1] * PACK_RECORD)), at + 8);
}
fs.mkdirSync(new URL('../assets/catalogs/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../assets/catalogs/hip-deep-v1.db', import.meta.url), pack);
const deepMags = deepRows.map((r) => r.mag / 100);
fs.writeFileSync(new URL('deepPack.ts', out),
  `// Generated by scripts/build-data.mjs. Do not edit.
` +
  `export const DEEP_PACK = ${JSON.stringify({
    id: 'hip-deep-v1', stars: deepRows.length, bytes: pack.length, sha256: crypto.createHash('sha256').update(pack).digest('hex'),
    magnitudeFrom: Math.min(...deepMags.slice(0, 200000)), magnitudeTo: deepMags.reduce((a, b) => Math.max(a, b), -99), source: 'Hipparcos Main Catalogue, the same input as the bundled stars',
  })} as const;
`);

// Boundaries stay in their own file: only the sky chart needs them.
fs.writeFileSync(new URL('boundaries.json', out), JSON.stringify(constellations.map(({ id, bounds }) => ({ id, bounds }))));

console.log({ deepStars: deepRows.length, deepBytes: pack.length });
console.log({ stars: rows.length, bytes: packed.length, meta: metaRows.length, deep: deep.length, constellations: constellations.length });
